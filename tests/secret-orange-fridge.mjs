import assert from 'node:assert/strict';
import fs from 'node:fs';
import {loadGame} from './fixture.mjs';
const {game:g,elements,setup,advance,cleanup}=await loadGame('main',{saved:14,unlocked:14});
const stand=(platform,x,z)=>{g.state.platform=platform;g.player.root.position.set(x,platform?.height??0,z);g.player.lastStepPosition.copy(g.player.root.position);g.scene.updateMatrixWorld(true);};
const photoClasses=new Set();
elements['secret-photo'].classList={add:value=>photoClasses.add(value),remove:value=>photoClasses.delete(value)};
try{
 setup();g.state.ownerNext=Infinity;
 const counter=g.platforms.find(p=>p.id==='counter'),step=g.platforms.find(p=>p.id==='fridge-step'),top=g.platforms.find(p=>p.id==='fridge-top');
 const oranges=g.props.filter(p=>p.orange);
 assert.equal(oranges.length,4);
 stand(counter,3.4,-3.92);
 for(const orange of oranges){
   assert(g.selectInteraction(orange.id),'each orange can be selected');g.interact();advance(1.6);
   assert(Number.isFinite(orange.started),'orange fell '+orange.id);
   assert(orange.node.position.y<.15,'orange is on floor '+orange.id);
   assert(!g.canReach(orange),'fallen orange cannot be re-used on counter');
 }
 assert(!g.state.orangesNoticed,'owner has not found the oranges yet');
 assert(oranges.every(p=>p.node.position.y<.15),'all oranges persist on floor');
 advance(22);
 assert(g.state.orangesNoticed,'Ah Ching discovers the four oranges');
 assert.equal(globalThis.localStorage.getItem('cat-house-secret-orange'),'1','secret collected after cleanup');
 assert(oranges.every(p=>!Number.isFinite(p.started)),'Ah Ching returns each orange');
 assert.equal(elements['secret-photo'].src,'/assets/records/secret-orange.webp');
 assert(photoClasses.has('record-loading'),'previous photo remains concealed until the new one loads');
 elements['secret-photo'].emit('load');assert(!photoClasses.has('record-loading'));
 elements['secret-album'].emit('click');assert(elements.album.open);assert.equal(elements['album-grid'].children.length,20);assert.match(elements['album-large'].src,/secret-orange\.webp$/);elements.album.close();
 g.reset();g.state.ownerNext=Infinity;
 stand(counter,7.08,-3.78);
 assert(g.jump(),'normal jump from counter reaches the small ledge');advance(1);
 assert.equal(g.state.platform,step);
 assert(g.jump(),'normal jump from ledge reaches the fridge roof');advance(1);
 assert.equal(g.state.platform,top);
 assert(elements.toast.hidden,'landing on fridge does not give away the secret solution');
 assert(!g.jumpDown(),'cat cannot jump down');
 assert(!/按 R|大聲叫/.test(elements.toast.textContent),'failed jump keeps the clue implicit');
 g.meow(false);assert.equal(g.state.fridgeRescue.stage,'stranded');
 advance(.6);g.meow(true);assert.equal(g.state.fridgeRescue.stage,'coming');
 advance(22);
 assert.equal(globalThis.localStorage.getItem('cat-house-secret-fridge'),'1','rescue completes secret');
 assert.equal(g.state.platform,null,'cat is back on the floor');
 assert.equal(elements['secret-photo'].src,'/assets/records/secret-fridge.webp');
 assert(photoClasses.has('record-loading'),'earlier orange photo is concealed during fridge photo load');
 assert.equal(elements['secret-title'].textContent,'最高處的求救聲');
 elements['secret-photo'].emit('load');assert(!photoClasses.has('record-loading'));
 for(const name of ['orange','fridge'])assert(fs.statSync(new URL('../dist/assets/records/secret-'+name+'.webp',import.meta.url)).size>100_000);
 console.log('PASS secrets: four persistent oranges, owner scolds and restores, fridge ledge, stranded meow rescue, both album photos.');
}finally{cleanup();}
